package com.alw.workstation.core.proot.provisioning

/**
 * Configuration parameters for the automated Arch Linux ARM rootfs provisioning sequence.
 */
data class ProvisioningConfig(
    val defaultUser: String = "alw",
    val shell: String = "/bin/bash",
    val configurePacmanKeys: Boolean = true,
    val ignoreKernelPackages: Boolean = true,
    val updateSystem: Boolean = true,
    val installCorePackages: Boolean = true,
    val additionalPackages: List<String> = emptyList(),
    val installAurWrapper: Boolean = true,
    val configureWaylandFlags: Boolean = true,
    val configureChromiumSandboxFlags: Boolean = true,
    val configureAudioBridge: Boolean = true
) {
    companion object {
        val defaultCorePackages = listOf(
            "xorg-xwayland",
            "mesa",
            "mesa-utils",
            "vulkan-tools",
            "pipewire",
            "pipewire-pulse",
            "wireplumber",
            "hyprland",
            "labwc",
            "kitty",
            "neovim",
            "git",
            "sudo",
            "base-devel",
            "fastfetch",
            "fakeroot-tcp"
        )
    }
}

/**
 * Builds the automated rootfs provisioning shell script.
 * Encapsulates pacman keyring initialization, package installations, user creation,
 * AUR makepkg -A wrapper, and global Wayland/Electron sandbox flags.
 */
object ArchProvisioningScriptBuilder {

    fun buildScript(config: ProvisioningConfig): String {
        val allPackages = (ProvisioningConfig.defaultCorePackages + config.additionalPackages).distinct()
        val totalSteps = 8

        return buildString {
            appendLine("#!/bin/bash")
            appendLine("set -eo pipefail")
            appendLine()

            // Ensure DNS resolution and disable Pacman 7 sandbox inside unrooted PRoot
            appendLine("# Ensure /etc/resolv.conf is a regular file with valid nameservers")
            appendLine("if [ ! -f /etc/resolv.conf ] || [ -L /etc/resolv.conf ]; then")
            appendLine("    rm -f /etc/resolv.conf")
            appendLine("    printf 'nameserver 1.1.1.1\\nnameserver 8.8.8.8\\n' > /etc/resolv.conf")
            appendLine("    chmod 644 /etc/resolv.conf")
            appendLine("fi")
            appendLine("# Disable Pacman 7 download and hook sandbox inside unrooted PRoot")
            appendLine("if [ -f /etc/pacman.conf ]; then")
            appendLine("    if grep -q '^#DisableSandbox' /etc/pacman.conf; then")
            appendLine("        sed -i 's/^#DisableSandbox/DisableSandbox/' /etc/pacman.conf")
            appendLine("    elif ! grep -q '^DisableSandbox' /etc/pacman.conf; then")
            appendLine("        sed -i '/\\[options\\]/a DisableSandbox' /etc/pacman.conf")
            appendLine("    fi")
            appendLine("fi")
            appendLine()

            // Step 1: Pacman keyrings
            appendLine("echo '==> Step 1/$totalSteps: Initializing pacman keyrings...'")
            if (config.configurePacmanKeys) {
                appendLine("pacman-key --init || true")
                appendLine("pacman-key --populate archlinuxarm || true")
            } else {
                appendLine("echo 'Pacman keyrings skipped by config'")
            }
            appendLine()

            // Step 2: Configure pacman ignores, mirrors, sync and update
            appendLine("echo '==> Step 2/$totalSteps: Configuring package ignores and synchronizing repositories...'")
            appendLine("# Ensure reliable high-speed Arch Linux ARM mirrors are prioritized")
            appendLine("if [ -f /etc/pacman.d/mirrorlist ]; then")
            appendLine("    if ! grep -q 'mirrors.tuna.tsinghua.edu.cn' /etc/pacman.d/mirrorlist; then")
            appendLine("        printf 'Server = https://mirrors.tuna.tsinghua.edu.cn/archlinuxarm/\$arch/\$repo\\nServer = https://mirrors.ustc.edu.cn/archlinuxarm/\$arch/\$repo\\nServer = http://de4.mirror.archlinuxarm.org/\$arch/\$repo\\n' | cat - /etc/pacman.d/mirrorlist > /etc/pacman.d/mirrorlist.tmp && mv /etc/pacman.d/mirrorlist.tmp /etc/pacman.d/mirrorlist")
            appendLine("    fi")
            appendLine("fi")
            appendLine("# Ensure pacman DBPath is specified without a trailing slash to prevent PRoot stat ENOTDIR issues")
            appendLine("if [ -f /etc/pacman.conf ]; then")
            appendLine("    if ! grep -q '^DBPath' /etc/pacman.conf; then")
            appendLine("        sed -i '/\\[options\\]/a DBPath = /var/lib/pacman' /etc/pacman.conf")
            appendLine("    fi")
            appendLine("fi")
            if (config.ignoreKernelPackages) {
                appendLine("# Prevent kernel and initramfs hooks from executing inside PRoot")
                appendLine("if [ -f /etc/pacman.conf ]; then")
                appendLine("    if grep -q '^#IgnorePkg' /etc/pacman.conf; then")
                appendLine("        sed -i 's/^#IgnorePkg.*$/IgnorePkg = linux-aarch64 linux-firmware mkinitcpio/' /etc/pacman.conf")
                appendLine("    elif grep -q '^IgnorePkg' /etc/pacman.conf; then")
                appendLine("        sed -i 's/^IgnorePkg.*$/IgnorePkg = linux-aarch64 linux-firmware mkinitcpio/' /etc/pacman.conf")
                appendLine("    else")
                appendLine("        sed -i '/\\[options\\]/a IgnorePkg = linux-aarch64 linux-firmware mkinitcpio' /etc/pacman.conf")
                appendLine("    fi")
                appendLine("fi")
            }
            if (config.updateSystem) {
                appendLine("pacman -Syu --noconfirm || pacman -Sy --noconfirm || echo 'System sync warning, continuing'")
            } else {
                appendLine("echo 'System update skipped by config'")
            }
            appendLine()

            // Step 3: Install core workstation packages
            appendLine("echo '==> Step 3/$totalSteps: Installing core workstation packages...'")
            if (config.installCorePackages) {
                val packageListStr = allPackages.joinToString(" ")
                appendLine("pacman -S --noconfirm --needed $packageListStr || echo 'Core package installation warning, continuing'")
            } else {
                appendLine("echo 'Core package installation skipped by config'")
            }
            appendLine()

            // Step 4: Create default user & wheel sudoers
            appendLine("echo '==> Step 4/$totalSteps: Configuring user account and sudo permissions...'")
            appendLine("if ! id \"${config.defaultUser}\" >/dev/null 2>&1; then")
            appendLine("    useradd -m -s \"${config.shell}\" -G wheel \"${config.defaultUser}\"")
            appendLine("fi")
            appendLine("mkdir -p /etc/sudoers.d")
            appendLine("cat <<'EOF' > /etc/sudoers.d/00-wheel-nopasswd")
            appendLine("%wheel ALL=(ALL:ALL) NOPASSWD: ALL")
            appendLine()
            appendLine("EOF")
            appendLine("chmod 0440 /etc/sudoers.d/00-wheel-nopasswd")
            appendLine()

            // Step 5: AUR makepkg -A wrapper
            appendLine("echo '==> Step 5/$totalSteps: Installing native aarch64 makepkg AUR wrapper...'")
            if (config.installAurWrapper) {
                appendLine("mkdir -p /usr/local/bin")
                appendLine("cat <<'EOF' > /usr/local/bin/makepkg-wrapper")
                appendLine("#!/bin/bash")
                appendLine("exec /usr/bin/makepkg --mflags \"-A\" \"$@\"")
                appendLine("EOF")
                appendLine("chmod 0755 /usr/local/bin/makepkg-wrapper")
            } else {
                appendLine("echo 'AUR wrapper skipped by config'")
            }
            appendLine()

            // Step 6: Global Wayland, Turnip/Zink GPU, and compatibility flags
            appendLine("echo '==> Step 6/$totalSteps: Configuring global Wayland & Turnip/Zink GPU flags...'")
            if (config.configureWaylandFlags) {
                appendLine("cat <<'EOF' >> /etc/environment")
                appendLine("ELECTRON_OZONE_PLATFORM_HINT=wayland")
                appendLine("MOZ_ENABLE_WAYLAND=1")
                appendLine("QT_QPA_PLATFORM=wayland")
                appendLine("XDG_SESSION_TYPE=wayland")
                appendLine("UV_USE_IO_URING=0")
                appendLine("APPIMAGE_EXTRACT_AND_RUN=1")
                appendLine("MESA_LOADER_DRIVER_OVERRIDE=zink")
                appendLine("GALLIUM_DRIVER=zink")
                appendLine("TU_DEBUG=noconform")
                appendLine("VK_ICD_FILENAMES=/opt/drivers/turnip/active/freedreno_icd.aarch64.json")
                appendLine("VK_DRIVER_FILES=/opt/drivers/turnip/active/freedreno_icd.aarch64.json")
                appendLine("EOF")
                appendLine("cat <<'EOF' >> /etc/profile")
                appendLine("export UV_USE_IO_URING=0")
                appendLine("export APPIMAGE_EXTRACT_AND_RUN=1")
                appendLine("export MESA_LOADER_DRIVER_OVERRIDE=zink")
                appendLine("export GALLIUM_DRIVER=zink")
                appendLine("export TU_DEBUG=noconform")
                appendLine("export VK_ICD_FILENAMES=/opt/drivers/turnip/active/freedreno_icd.aarch64.json")
                appendLine("export VK_DRIVER_FILES=/opt/drivers/turnip/active/freedreno_icd.aarch64.json")
                appendLine("EOF")
            }
            if (config.configureChromiumSandboxFlags) {
                appendLine("mkdir -p /etc")
                appendLine("cat <<'EOF' > /etc/chromium-flags.conf")
                appendLine("--ozone-platform-hint=wayland")
                appendLine("--no-sandbox")
                appendLine("--disable-gpu-sandbox")
                appendLine("EOF")
            }
            appendLine()

            // Step 7: Low-latency PulseAudio and PipeWire client configuration
            appendLine("echo '==> Step 7/$totalSteps: Configuring low-latency PulseAudio & PipeWire bridge...'")
            if (config.configureAudioBridge) {
                appendLine("mkdir -p /etc/pulse")
                appendLine("cat <<'EOF' > /etc/pulse/client.conf")
                appendLine("default-server = unix:/tmp/runtime-alw/pulse/native")
                appendLine("autospawn = no")
                appendLine("daemon-binary = /bin/true")
                appendLine("enable-shm = false")
                appendLine("EOF")
                appendLine("mkdir -p /run/user/1000")
                appendLine("ln -sfn /tmp/runtime-alw/pulse /run/user/1000/pulse")
                appendLine("cat <<'EOF' >> /etc/environment")
                appendLine("PULSE_SERVER=unix:/run/user/1000/pulse/native unix:/tmp/runtime-alw/pulse/native")
                appendLine("PIPEWIRE_RUNTIME_DIR=/tmp/runtime-alw")
                appendLine("EOF")
            } else {
                appendLine("echo 'Audio bridge configuration skipped by config'")
            }
            appendLine()

            // Step 8: Android PTY & Pacman root access compatibility shim
            appendLine("echo '==> Step 8/$totalSteps: Materializing Android PTY & Pacman access shim...'")
            appendLine("if which gcc >/dev/null 2>&1; then")
            appendLine("    cat <<'EOF' > /tmp/alw_shim.c")
            appendLine("#define _GNU_SOURCE")
            appendLine("#include <stdio.h>")
            appendLine("#include <stdlib.h>")
            appendLine("#include <string.h>")
            appendLine("#include <unistd.h>")
            appendLine("#include <errno.h>")
            appendLine("#include <dlfcn.h>")
            appendLine("#include <stdarg.h>")
            appendLine("#include <fcntl.h>")
            appendLine("#include <sys/types.h>")
            appendLine("#include <sys/stat.h>")
            appendLine("#include <termios.h>")
            appendLine("#include <sys/ioctl.h>")
            appendLine("#include <sys/socket.h>")
            appendLine("#include <linux/netlink.h>")
            appendLine()
            appendLine("static int s_netlink_fds[128];")
            appendLine("static int s_netlink_count = 0;")
            appendLine()
            appendLine("static int is_netlink_fd(int fd) {")
            appendLine("    for (int i = 0; i < s_netlink_count; i++) {")
            appendLine("        if (s_netlink_fds[i] == fd) return 1;")
            appendLine("    }")
            appendLine("    return 0;")
            appendLine("}")
            appendLine()
            appendLine("int socket(int domain, int type, int protocol) {")
            appendLine("    static int (*real_socket)(int, int, int) = NULL;")
            appendLine("    if (!real_socket) real_socket = dlsym(RTLD_NEXT, \"socket\");")
            appendLine("    int fd = real_socket ? real_socket(domain, type, protocol) : -1;")
            appendLine("    if (fd < 0 && domain == AF_NETLINK) {")
            appendLine("        int sv[2];")
            appendLine("        if (socketpair(AF_UNIX, (type & ~SOCK_NONBLOCK), 0, sv) == 0) {")
            appendLine("            if (type & SOCK_NONBLOCK) {")
            appendLine("                int flags = fcntl(sv[0], F_GETFL, 0);")
            appendLine("                fcntl(sv[0], F_SETFL, flags | O_NONBLOCK);")
            appendLine("            }")
            appendLine("            if (type & SOCK_CLOEXEC) {")
            appendLine("                int flags = fcntl(sv[0], F_GETFD, 0);")
            appendLine("                fcntl(sv[0], F_SETFD, flags | FD_CLOEXEC);")
            appendLine("            }")
            appendLine("            close(sv[1]);")
            appendLine("            if (s_netlink_count < 128) {")
            appendLine("                s_netlink_fds[s_netlink_count++] = sv[0];")
            appendLine("            }")
            appendLine("            return sv[0];")
            appendLine("        }")
            appendLine("    }")
            appendLine("    return fd;")
            appendLine("}")
            appendLine()
            appendLine("int bind(int sockfd, const struct sockaddr *addr, socklen_t addrlen) {")
            appendLine("    if (is_netlink_fd(sockfd) || (addr && addr->sa_family == AF_NETLINK)) {")
            appendLine("        return 0;")
            appendLine("    }")
            appendLine("    static int (*real_bind)(int, const struct sockaddr *, socklen_t) = NULL;")
            appendLine("    if (!real_bind) real_bind = dlsym(RTLD_NEXT, \"bind\");")
            appendLine("    return real_bind ? real_bind(sockfd, addr, addrlen) : -1;")
            appendLine("}")
            appendLine()
            appendLine("int setsockopt(int sockfd, int level, int optname, const void *optval, socklen_t optlen) {")
            appendLine("    if (is_netlink_fd(sockfd)) {")
            appendLine("        return 0;")
            appendLine("    }")
            appendLine("    static int (*real_setsockopt)(int, int, int, const void *, socklen_t) = NULL;")
            appendLine("    if (!real_setsockopt) real_setsockopt = dlsym(RTLD_NEXT, \"setsockopt\");")
            appendLine("    return real_setsockopt ? real_setsockopt(sockfd, level, optname, optval, optlen) : -1;")
            appendLine("}")
            appendLine()
            appendLine("int getsockname(int sockfd, struct sockaddr *addr, socklen_t *addrlen) {")
            appendLine("    if (is_netlink_fd(sockfd)) {")
            appendLine("        if (addr && addrlen && *addrlen >= sizeof(struct sockaddr_nl)) {")
            appendLine("            struct sockaddr_nl *nl = (struct sockaddr_nl *)addr;")
            appendLine("            memset(nl, 0, sizeof(*nl));")
            appendLine("            nl->nl_family = AF_NETLINK;")
            appendLine("            nl->nl_pid = getpid();")
            appendLine("            *addrlen = sizeof(struct sockaddr_nl);")
            appendLine("            return 0;")
            appendLine("        }")
            appendLine("    }")
            appendLine("    static int (*real_getsockname)(int, struct sockaddr *, socklen_t *) = NULL;")
            appendLine("    if (!real_getsockname) real_getsockname = dlsym(RTLD_NEXT, \"getsockname\");")
            appendLine("    return real_getsockname ? real_getsockname(sockfd, addr, addrlen) : -1;")
            appendLine("}")
            appendLine()
            appendLine("int close(int fd) {")
            appendLine("    static int (*real_close)(int) = NULL;")
            appendLine("    if (!real_close) real_close = dlsym(RTLD_NEXT, \"close\");")
            appendLine("    for (int i = 0; i < s_netlink_count; i++) {")
            appendLine("        if (s_netlink_fds[i] == fd) {")
            appendLine("            s_netlink_fds[i] = -1;")
            appendLine("            break;")
            appendLine("        }")
            appendLine("    }")
            appendLine("    return real_close ? real_close(fd) : -1;")
            appendLine("}")
            appendLine()
            appendLine("int access(const char *pathname, int mode) {")
            appendLine("    static int (*real_access)(const char*, int) = NULL;")
            appendLine("    if (!real_access) real_access = dlsym(RTLD_NEXT, \"access\");")
            appendLine("    int ret = real_access ? real_access(pathname, mode) : -1;")
            appendLine("    if (ret != 0 && (mode & W_OK) && pathname && pathname[0] == '/' && errno == EACCES) return 0;")
            appendLine("    return ret;")
            appendLine("}")
            appendLine()
            appendLine("int faccessat(int dirfd, const char *pathname, int mode, int flags) {")
            appendLine("    static int (*real_faccessat)(int, const char*, int, int) = NULL;")
            appendLine("    if (!real_faccessat) real_faccessat = dlsym(RTLD_NEXT, \"faccessat\");")
            appendLine("    if (pathname && pathname[0] == '/') {")
            appendLine("        if (access(pathname, mode) == 0) return 0;")
            appendLine("    }")
            appendLine("    int ret = real_faccessat ? real_faccessat(dirfd, pathname, mode, flags) : -1;")
            appendLine("    if (ret != 0 && (mode & W_OK) && pathname && errno == EACCES) return 0;")
            appendLine("    if (ret != 0 && pathname && pathname[0] == '/') {")
            appendLine("        if (access(pathname, mode) == 0) return 0;")
            appendLine("    }")
            appendLine("    return ret;")
            appendLine("}")
            appendLine()
            appendLine("int faccessat2(int dirfd, const char *pathname, int mode, int flags) {")
            appendLine("    static int (*real_faccessat2)(int, const char*, int, int) = NULL;")
            appendLine("    if (!real_faccessat2) real_faccessat2 = dlsym(RTLD_NEXT, \"faccessat2\");")
            appendLine("    if (pathname && pathname[0] == '/') {")
            appendLine("        if (access(pathname, mode) == 0) return 0;")
            appendLine("    }")
            appendLine("    int ret = real_faccessat2 ? real_faccessat2(dirfd, pathname, mode, flags) : -1;")
            appendLine("    if (ret != 0 && (mode & W_OK) && pathname && errno == EACCES) return 0;")
            appendLine("    if (ret != 0 && pathname && pathname[0] == '/') {")
            appendLine("        if (access(pathname, mode) == 0) return 0;")
            appendLine("    }")
            appendLine("    return ret;")
            appendLine("}")
            appendLine()
            appendLine("int ttyname_r(int fd, char *buf, size_t buflen) {")
            appendLine("    static int (*real_ttyname_r)(int, char*, size_t) = NULL;")
            appendLine("    if (!real_ttyname_r) real_ttyname_r = dlsym(RTLD_NEXT, \"ttyname_r\");")
            appendLine("    int ret = real_ttyname_r ? real_ttyname_r(fd, buf, buflen) : -1;")
            appendLine("    if (ret == 0) return 0;")
            appendLine("    char procpath[64];")
            appendLine("    snprintf(procpath, sizeof(procpath), \"/proc/self/fd/%d\", fd);")
            appendLine("    ssize_t len = readlink(procpath, buf, buflen - 1);")
            appendLine("    if (len > 0) { buf[len] = '\\0'; return 0; }")
            appendLine("    return ret;")
            appendLine("}")
            appendLine()
            appendLine("char *ttyname(int fd) {")
            appendLine("    static char s_ttyname_buf[1024];")
            appendLine("    if (ttyname_r(fd, s_ttyname_buf, sizeof(s_ttyname_buf)) == 0) return s_ttyname_buf;")
            appendLine("    return NULL;")
            appendLine("}")
            appendLine()
            appendLine("int isatty(int fd) {")
            appendLine("    static int (*real_isatty)(int) = NULL;")
            appendLine("    if (!real_isatty) real_isatty = dlsym(RTLD_NEXT, \"isatty\");")
            appendLine("    if (real_isatty && real_isatty(fd) == 1) return 1;")
            appendLine("    char procpath[64], target[256];")
            appendLine("    snprintf(procpath, sizeof(procpath), \"/proc/self/fd/%d\", fd);")
            appendLine("    ssize_t len = readlink(procpath, target, sizeof(target) - 1);")
            appendLine("    if (len > 0) {")
            appendLine("        target[len] = '\\0';")
            appendLine("        if (strstr(target, \"/dev/pts/\") || strstr(target, \"/dev/tty\")) return 1;")
            appendLine("    }")
            appendLine("    return 0;")
            appendLine("}")
            appendLine()
            appendLine("int tcgetattr(int fd, struct termios *termios_p) {")
            appendLine("    static int (*real_tcgetattr)(int, struct termios*) = NULL;")
            appendLine("    if (!real_tcgetattr) real_tcgetattr = dlsym(RTLD_NEXT, \"tcgetattr\");")
            appendLine("    int ret = real_tcgetattr ? real_tcgetattr(fd, termios_p) : -1;")
            appendLine("    if (ret == 0) return 0;")
            appendLine("    if (errno == EACCES && isatty(fd)) {")
            appendLine("        if (termios_p) {")
            appendLine("            memset(termios_p, 0, sizeof(*termios_p));")
            appendLine("            termios_p->c_iflag = ICRNL | IXON;")
            appendLine("            termios_p->c_oflag = OPOST | ONLCR;")
            appendLine("            termios_p->c_cflag = CS8 | CREAD | HUPCL;")
            appendLine("            termios_p->c_lflag = ISIG | ICANON | ECHO | ECHOE | ECHOK | ECHOCTL | ECHOKE | IEXTEN;")
            appendLine("            termios_p->c_cc[VINTR] = 003; termios_p->c_cc[VQUIT] = 034;")
            appendLine("            termios_p->c_cc[VERASE] = 0177; termios_p->c_cc[VKILL] = 025;")
            appendLine("            termios_p->c_cc[VEOF] = 004; termios_p->c_cc[VSTART] = 021;")
            appendLine("            termios_p->c_cc[VSTOP] = 023; termios_p->c_cc[VSUSP] = 032;")
            appendLine("            cfsetispeed(termios_p, B38400); cfsetospeed(termios_p, B38400);")
            appendLine("        }")
            appendLine("        return 0;")
            appendLine("    }")
            appendLine("    return ret;")
            appendLine("}")
            appendLine()
            appendLine("int tcsetattr(int fd, int optional_actions, const struct termios *termios_p) {")
            appendLine("    static int (*real_tcsetattr)(int, int, const struct termios*) = NULL;")
            appendLine("    if (!real_tcsetattr) real_tcsetattr = dlsym(RTLD_NEXT, \"tcsetattr\");")
            appendLine("    int ret = real_tcsetattr ? real_tcsetattr(fd, optional_actions, termios_p) : -1;")
            appendLine("    if (ret == 0) return 0;")
            appendLine("    if (errno == EACCES && isatty(fd)) return 0;")
            appendLine("    return ret;")
            appendLine("}")
            appendLine()
            appendLine("int ioctl(int fd, unsigned long request, ...) {")
            appendLine("    static int (*real_ioctl)(int, unsigned long, void*) = NULL;")
            appendLine("    if (!real_ioctl) real_ioctl = dlsym(RTLD_NEXT, \"ioctl\");")
            appendLine("    va_list args; va_start(args, request); void *argp = va_arg(args, void*); va_end(args);")
            appendLine("    int ret = real_ioctl ? real_ioctl(fd, request, argp) : -1;")
            appendLine("    if (ret != 0 && errno == EACCES && isatty(fd)) return 0;")
            appendLine("    return ret;")
            appendLine("}")
            appendLine()
            appendLine("static int find_pts_fd_fallback(const char *pathname) {")
            appendLine("    if (!pathname || strncmp(pathname, \"/dev/pts/\", 9) != 0) return -1;")
            appendLine("    for (int fd = 0; fd < 64; fd++) {")
            appendLine("        char target[64], procpath[64];")
            appendLine("        snprintf(procpath, sizeof(procpath), \"/proc/self/fd/%d\", fd);")
            appendLine("        ssize_t len = readlink(procpath, target, sizeof(target) - 1);")
            appendLine("        if (len > 0) {")
            appendLine("            target[len] = '\\0';")
            appendLine("            if (strcmp(target, pathname) == 0) return dup(fd);")
            appendLine("        }")
            appendLine("    }")
            appendLine("    return -1;")
            appendLine("}")
            appendLine()
            appendLine("int open(const char *pathname, int flags, ...) {")
            appendLine("    static int (*real_open)(const char*, int, mode_t) = NULL;")
            appendLine("    if (!real_open) real_open = dlsym(RTLD_NEXT, \"open\");")
            appendLine("    mode_t mode = 0;")
            appendLine("    if (flags & O_CREAT) { va_list args; va_start(args, flags); mode = va_arg(args, mode_t); va_end(args); }")
            appendLine("    int ret = real_open ? real_open(pathname, flags, mode) : -1;")
            appendLine("    if (ret == -1) { int dupfd = find_pts_fd_fallback(pathname); if (dupfd >= 0) return dupfd; }")
            appendLine("    return ret;")
            appendLine("}")
            appendLine()
            appendLine("int open64(const char *pathname, int flags, ...) {")
            appendLine("    static int (*real_open64)(const char*, int, mode_t) = NULL;")
