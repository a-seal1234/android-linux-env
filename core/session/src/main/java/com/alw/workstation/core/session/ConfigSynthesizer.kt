package com.alw.workstation.core.session

import com.alw.workstation.core.session.model.StackProfile

/**
 * Non-destructive session configuration synthesizer.
 * Generates runtime session overrides in /tmp/ without modifying user dotfiles.
 */
object ConfigSynthesizer {

    /**
     * Synthesizes a Hyprland session override config that sources the user's authentic
     * ~/.config/hypr/hyprland.conf first, then appends hardware and workstation overrides.
     */
    fun synthesizeHyprlandConfig(profile: StackProfile): String {
        val userConfig = profile.compositor.userConfigPath ?: "~/.config/hypr/hyprland.conf"
        val width = profile.display.customWidth ?: 3200
        val height = profile.display.customHeight ?: 2136
        val rate = profile.display.refreshRateHz
        val scale = profile.display.scaleFactor

        return buildString {
            appendLine("# Auto-generated by Android Linux Workstation (ALW) - DO NOT EDIT MANUALLY")
            appendLine("# Step 1: Source the user's authentic config first (preserves user customizations)")
            appendLine("source = $userConfig")
            appendLine()
            appendLine("# Step 2: Workstation display & Wayland bridge overrides")
            appendLine("monitor = WL-1, ${width}x${height}@${rate}, 0x0, $scale")
            appendLine()
            appendLine("input {")
            appendLine("    kb_layout = us")
            if (profile.input.rebindCapsToSuper) {
                appendLine("    kb_options = ${profile.input.xkbOptions}")
            }
            appendLine("    follow_mouse = 1")
            appendLine("    touchpad {")
            appendLine("        natural_scroll = ${profile.input.touchpadNaturalScroll}")
            appendLine("    }")
            appendLine("}")
            appendLine()
            appendLine("env = WAYLAND_DISPLAY,wayland-0")
            appendLine("env = XDG_CURRENT_DESKTOP,Hyprland")
            appendLine("env = ELECTRON_OZONE_PLATFORM_HINT,wayland")
        }
    }
}
