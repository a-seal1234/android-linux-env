package com.alw.workstation.core.session

import com.alw.workstation.core.session.model.StackProfile
import java.io.File

/**
 * Non-destructive session configuration synthesizer.
 * Generates runtime session overrides in /tmp/ and scaffolds default compositor
 * configurations for first boot without destructively overwriting user customizations.
 */
object ConfigSynthesizer {

    /**
     * Synthesizes the Hyprland session override in Hyprland >= 0.57's Lua config
     * format (`Config::Lua::CConfigManager`). The legacy INI dialect is silently
     * ignored by 0.57, which is why Xwayland kept spawning and stdout logging stayed
     * disabled. Only verified 0.57 config keys are emitted.
     */
    fun synthesizeHyprlandSessionConfig(profile: StackProfile): String {
        val scale = profile.display.scaleFactor
        val isSoftwareRendering = profile.gpu.driverMode == StackProfile.DriverMode.LLVMPIPE

        return buildString {
            appendLine("-- Auto-generated by Android Linux Workstation (ALW) - DO NOT EDIT MANUALLY")
            appendLine("-- Hyprland >= 0.57 Lua session override for the nested Aquamarine backend.")
            appendLine("-- User configuration stays untouched at ${profile.compositor.userConfigPath}.")
            appendLine()
            appendLine("hl.config({")
            appendLine("    xwayland = { enabled = false },")
            appendLine("    cursor = { no_hardware_cursors = 1 },")
            appendLine("    debug = { enable_stdout_logs = true },")
            appendLine("    misc = {")
            appendLine("        disable_hyprland_logo = true,")
            appendLine("        disable_splash_rendering = true,")
            appendLine("    },")
            appendLine("    input = {")
            appendLine("        kb_layout = \"us\",")
            appendLine("        follow_mouse = 1,")
            appendLine("        touchpad = { natural_scroll = ${profile.input.touchpadNaturalScroll} },")
            appendLine("    },")
            appendLine("    decoration = {")
            if (isSoftwareRendering) {
                appendLine("        rounding = 0,")
                appendLine("        blur = { enabled = false },")
            } else {
                appendLine("        rounding = 8,")
                appendLine("        blur = { enabled = true, size = 5, passes = 2 },")
            }
            appendLine("    },")
            appendLine("})")
            appendLine()
            appendLine("hl.monitor({ output = \"\", mode = \"preferred\", position = \"auto\", scale = \"$scale\" })")
            appendLine()
            appendLine("hl.env(\"WAYLAND_DISPLAY\", \"wayland-0\")")
            appendLine("hl.env(\"XDG_CURRENT_DESKTOP\", \"Hyprland\")")
            appendLine("hl.env(\"ELECTRON_OZONE_PLATFORM_HINT\", \"wayland\")")
            appendLine("hl.env(\"AQ_BACKEND\", \"wayland\")")
            appendLine("hl.env(\"WLR_BACKENDS\", \"wayland\")")
            appendLine("hl.env(\"WLR_NO_HARDWARE_CURSORS\", \"1\")")
            appendLine("hl.env(\"AQ_NO_MODIFIERS\", \"1\")")
            appendLine("-- PRoot has no systemd-logind/seatd session; Hyprland must use the noop seat backend")
            appendLine("hl.env(\"LIBSEAT_BACKEND\", \"noop\")")
            appendLine()
            appendLine("hl.bind(\"SUPER + Return\", hl.dsp.exec_cmd(\"kitty\"))")
            appendLine("hl.bind(\"SUPER + Q\", hl.dsp.window.close())")
            appendLine("hl.bind(\"SUPER + M\", hl.dsp.exit())")
            appendLine()
            appendLine("hl.on(\"hyprland.start\", function()")
            appendLine("    hl.exec_cmd(\"konsole --hold -e /bin/bash -c 'fastfetch; exec bash'\")")
            appendLine("end)")
        }
    }

    /**
     * Generates a clean default user configuration for Hyprland (~/.config/hypr/hyprland.conf).
     */
    fun generateDefaultHyprlandUserConfig(): String {
        return buildString {
            appendLine("# Xiaomi Pad 8 Default Hyprland Configuration")
            appendLine("# Managed by user; ALW sources this file before runtime overrides.")
            appendLine()
            appendLine("monitor = , preferred, auto, 1.75")
            appendLine()
            appendLine("\$terminal = kitty")
            appendLine("\$mainMod = SUPER")
            appendLine()
            appendLine("bind = \$mainMod, Return, exec, \$terminal")
            appendLine("bind = \$mainMod, Q, killactive,")
            appendLine("bind = \$mainMod, M, exit,")
            appendLine()
            appendLine("input {")
            appendLine("    kb_layout = us")
            appendLine("    follow_mouse = 1")
            appendLine("    touchpad {")
            appendLine("        natural_scroll = true")
            appendLine("    }")
            appendLine("    tablet {")
            appendLine("        output = WL-1")
            appendLine("    }")
            appendLine("    touchdevice {")
            appendLine("        output = WL-1")
            appendLine("    }")
            appendLine("}")
            appendLine()
            appendLine("general {")
            appendLine("    gaps_in = 4")
            appendLine("    gaps_out = 8")
            appendLine("    border_size = 2")
            appendLine("    col.active_border = rgba(33ccffee) rgba(00ff99ee) 45deg")
            appendLine("    col.inactive_border = rgba(595959aa)")
            appendLine("    layout = dwindle")
            appendLine("}")
            appendLine()
            appendLine("dwindle {")
            appendLine("    pseudotile = true")
            appendLine("    preserve_split = true")
            appendLine("}")
        }
    }

    /**
     * Generates a clean Openbox-compliant rc.xml for LabWC Safe Mode (~/.config/labwc/rc.xml).
     */
    fun generateDefaultLabwcRcXml(profile: StackProfile): String {
        return buildString {
            appendLine("<?xml version=\"1.0\"?>")
            appendLine("<labwc_config>")
            appendLine("  <theme>")
            appendLine("    <name>Openbox</name>")
            appendLine("    <titlebar>")
            appendLine("      <layout>NL:IMC</layout>")
            appendLine("    </titlebar>")
            appendLine("  </theme>")
            appendLine("  <core>")
            appendLine("    <decoration>server</decoration>")
            appendLine("    <gap>4</gap>")
            appendLine("  </core>")
            appendLine("  <windowRules>")
            appendLine("    <windowRule identifier=\"*\" serverDecoration=\"yes\" />")
            appendLine("  </windowRules>")
            appendLine("  <keyboard>")
            appendLine("    <keybind key=\"W-Return\"><action name=\"Execute\" command=\"weston-terminal --shell=/usr/bin/bash\" /></keybind>")
            appendLine("    <keybind key=\"A-Return\"><action name=\"Execute\" command=\"kitty\" /></keybind>")
            appendLine("    <keybind key=\"W-q\"><action name=\"Close\" /></keybind>")
            appendLine("    <keybind key=\"W-m\"><action name=\"Exit\" /></keybind>")
            appendLine("  </keyboard>")
            appendLine("  <touch>")
            appendLine("    <naturalScroll>${profile.input.touchpadNaturalScroll}</naturalScroll>")
            appendLine("  </touch>")
            appendLine("</labwc_config>")
        }
    }

    /**
     * Generates default autostart script for LabWC Safe Mode (~/.config/labwc/autostart).
     */
    fun generateDefaultLabwcAutostart(): String {
        return buildString {
            appendLine("#!/bin/sh")
            appendLine("# LabWC Safe Mode autostart")
            appendLine("which pipewire >/dev/null 2>&1 && pipewire &")
            appendLine("which wireplumber >/dev/null 2>&1 && wireplumber &")
            appendLine("if which weston-terminal >/dev/null 2>&1; then")
            appendLine("    weston-terminal --shell=/usr/bin/bash &")
            appendLine("elif which kitty >/dev/null 2>&1; then")
            appendLine("    kitty &")
            appendLine("elif which foot >/dev/null 2>&1; then")
            appendLine("    foot &")
            appendLine("fi")
        }
    }

    /**
     * Ensures default configs exist for the specified rootfs without overwriting existing user dotfiles.
     */
    fun ensureDefaultConfigsExist(rootfsDir: File, defaultUser: String, profile: StackProfile) {
        val userHome = File(rootfsDir, "home/$defaultUser")
        val hyprConfigDir = File(userHome, ".config/hypr")
        val hyprConfigFile = File(hyprConfigDir, "hyprland.conf")

        if (!hyprConfigFile.exists()) {
            hyprConfigDir.mkdirs()
            hyprConfigFile.writeText(generateDefaultHyprlandUserConfig())
        }

        val labwcConfigDir = File(userHome, ".config/labwc")
        val labwcConfigFile = File(labwcConfigDir, "rc.xml")
        val labwcAutostartFile = File(labwcConfigDir, "autostart")

        if (!labwcConfigFile.exists()) {
            labwcConfigDir.mkdirs()
            labwcConfigFile.writeText(generateDefaultLabwcRcXml(profile))
        }

        if (!labwcAutostartFile.exists()) {
            labwcConfigDir.mkdirs()
            labwcAutostartFile.writeText(generateDefaultLabwcAutostart())
            labwcAutostartFile.setExecutable(true, false)
        }
    }
}
