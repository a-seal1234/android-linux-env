package com.alw.workstation.core.session

import com.alw.workstation.core.session.model.StackProfile
import java.io.File

/**
 * Non-destructive session configuration synthesizer.
 * Generates runtime session overrides in /tmp/ and scaffolds default compositor
 * configurations for first boot without destructively overwriting user customizations.
 */
object ConfigSynthesizer {

    /**
     * Synthesizes the Hyprland session override in Hyprland >= 0.57's Lua config
     * format (`Config::Lua::CConfigManager`). The legacy INI dialect is silently
     * ignored by 0.57, which is why Xwayland kept spawning and stdout logging stayed
     * disabled. Only verified 0.57 config keys are emitted.
     */
    fun synthesizeHyprlandSessionConfig(profile: StackProfile): String {
        val scale = profile.display.scaleFactor
        // The compositor only gets the GPU when the Phase 3b research toggle is on.
        // Otherwise it renders on Mesa's software path: llvmpipe (the explicit Safe Mode
        // profile) or kms_swrast, which EnvironmentGenerator pins for every Turnip
        // profile because zink cannot initialize GBM EGL on the virtual DRM node.
        // Treating only LLVMPIPE as "software" left blur and shadows enabled on the
        // default profile — the dominant frame-time cost of the 1-2 FPS baseline.
        val softwareCompositor = profile.gpu.driverMode == StackProfile.DriverMode.LLVMPIPE ||
            !profile.gpu.forceCompositorZink

        // Measurement aid for the GPU Blocker Gate: forces the compositor to present
        // every vsync (Hyprland's `misc:vfr = false`) so frame pacing can be measured
        // without synthesising input. Opt-in only — never a shipping default.
        val forceContinuousRendering = System.getenv("ALW_FORCE_CONTINUOUS") == "1" ||
            profile.gpu.environmentOverrides["ALW_FORCE_CONTINUOUS"] == "1"

        return buildString {
            appendLine("-- Auto-generated by Android Linux Workstation (ALW) - DO NOT EDIT MANUALLY")
            appendLine("-- Hyprland >= 0.57 Lua session override for the nested Aquamarine backend.")
            appendLine("-- The user configuration imported from the CachyOS host is loaded below and")
            appendLine("-- stays untouched at ${profile.compositor.userConfigPath}.")
            appendLine()
            appendLine("-- 1. Resolve modular require(...) calls from the imported user config.")
            appendLine("package.path = \"/home/alw/.config/hypr/?.lua;/home/alw/.config/hypr/?/init.lua;/root/.config/hypr/?.lua;\" .. package.path")
            appendLine()
            appendLine("-- 2. Load the user's Lua entry file. Keybinds/config load directly, and a")
            appendLine("--    host-specific helper failing must not abort the nested session.")
            appendLine("do")
            appendLine("    local entry = \"/home/alw/.config/hypr/hyprland.lua\"")
            appendLine("    local ok, err = pcall(dofile, entry)")
            appendLine("    if not ok then")
            appendLine("        print(\"[ALW] user hyprland.lua failed: \" .. tostring(err))")
            appendLine("        local okKeys, keysErr = pcall(dofile, \"/home/alw/.config/hypr/keybinds.lua\")")
            appendLine("        if not okKeys then print(\"[ALW] user keybinds.lua failed: \" .. tostring(keysErr)) end")
            appendLine("    end")
            appendLine("end")
            appendLine()
            appendLine("-- 3. Sekai Pop aesthetics (loaded only when deployed).")
            appendLine("pcall(dofile, \"/home/alw/.config/hypr/sekaipop-theme.lua\")")
            appendLine()
            appendLine("-- 4. Android/PRoot overrides re-applied AFTER the user config so host")
            appendLine("--    monitor/Xwayland/GPU settings cannot break the nested session.")
            appendLine("hl.config({")
            appendLine("    xwayland = { enabled = false },")
            appendLine("    -- Hardware/overlay cursors: the bridge composites the client cursor")
            appendLine("    -- sprite directly, so a mouse move no longer re-blits 3200x2136.")
            appendLine("    cursor = { no_hardware_cursors = 1 },")
            appendLine("    debug = { enable_stdout_logs = true },")
            appendLine("    misc = {")
            appendLine("        disable_hyprland_logo = true,")
            appendLine("        disable_splash_rendering = true,")
            if (forceContinuousRendering) {
                // Testing aid (ALW_FORCE_CONTINUOUS=1): disable variable refresh rate.
                // NOTE: measured on-device, this alone does NOT make Hyprland present
                // every vsync — it is damage-driven by design, so idle sessions stay
                // near-idle. Kept as the place to hang further pacing experiments.
                appendLine("        vfr = false,")
            }
            appendLine("    },")
            appendLine("    input = {")
            appendLine("        kb_layout = \"us\",")
            appendLine("        follow_mouse = 1,")
            appendLine("        touchpad = { natural_scroll = ${profile.input.touchpadNaturalScroll} },")
            appendLine("    },")
            appendLine("    decoration = {")
            if (softwareCompositor) {
                // Immediate llvmpipe relief (GPU Blocker Gate): blur and shadows are
                // per-pixel post-processing on a software rasterizer. Disabled
                // automatically and re-enabled automatically when the compositor runs
                // on the GPU (gpu.forceCompositorZink).
                appendLine("        blur = { enabled = false },")
                appendLine("        shadow = { enabled = false },")
            } else {
                appendLine("        blur = { enabled = true, size = 5, passes = 2 },")
                appendLine("        shadow = { enabled = true },")
            }
            appendLine("    },")
            appendLine("})")
            appendLine()
            appendLine("hl.monitor({ output = \"\", mode = \"preferred\", position = \"auto\", scale = \"$scale\" })")
            appendLine()
            appendLine("hl.env(\"WAYLAND_DISPLAY\", \"wayland-0\")")
            appendLine("hl.env(\"XDG_CURRENT_DESKTOP\", \"Hyprland\")")
            appendLine("hl.env(\"ELECTRON_OZONE_PLATFORM_HINT\", \"wayland\")")
            appendLine("hl.env(\"AQ_BACKEND\", \"wayland\")")
            appendLine("hl.env(\"WLR_BACKENDS\", \"wayland\")")
            appendLine("hl.env(\"AQ_NO_MODIFIERS\", \"1\")")
            appendLine("-- PRoot has no systemd-logind/seatd session; Hyprland must use the noop seat backend")
            appendLine("hl.env(\"LIBSEAT_BACKEND\", \"noop\")")
            appendLine()
            appendLine("-- Essential binds are re-registered last so they win over host-only launchers")
            appendLine("-- (uwsm/quickshell helpers are not installed in the guest).")
            appendLine("hl.bind(\"SUPER + Return\", hl.dsp.exec_cmd(\"kitty\"))")
            appendLine("hl.window_rule({ match = { class = \"^(kitty)$\" }, float = true, center = true,")
            appendLine("                   size = { \"monitor_w*0.62\", \"monitor_h*0.62\" } })")
            appendLine("hl.bind(\"SUPER + Q\", hl.dsp.window.close())")
            appendLine("hl.bind(\"SUPER + M\", hl.dsp.exit())")
            appendLine()
            appendLine("hl.on(\"hyprland.start\", function()")
            appendLine("    hl.exec_cmd(\"alw-gui-run kitty --hold -e /bin/bash -c 'fastfetch; exec bash'\")")
            appendLine("    -- Sekai Pop rice: wallpaper + status bar (no-ops when not installed).")
            appendLine("    -- hyprpaper first: swaybg's glycin loader needs bwrap, which PRoot forbids.")
            appendLine("    hl.exec_cmd(\"sh -c 'W=/home/alw/.config/hypr/assets/sekaipop-wallpaper.png; if command -v hyprpaper >/dev/null 2>&1; then alw-gui-run hyprpaper >/tmp/rt/hyprpaper.log 2>&1 & elif command -v swww >/dev/null 2>&1; then alw-gui-run swww-daemon >/dev/null 2>&1 & sleep 1; alw-gui-run swww img \$W >/dev/null 2>&1; elif command -v swaybg >/dev/null 2>&1; then alw-gui-run swaybg -i \$W -m fill >/tmp/rt/swaybg.log 2>&1 & fi'\")")
            appendLine("    -- Sekai Pop native shell (Quickshell) with Waybar fallback.")
            appendLine("    hl.exec_cmd(\"sh -c 'Q=/root/.config/quickshell/sekaipop; B=/home/alw/.config/waybar/sekaipop; if command -v qs >/dev/null 2>&1 && [ -d \$Q ]; then alw-gui-run qs -c sekaipop >/tmp/rt/quickshell.log 2>&1 & elif command -v waybar >/dev/null 2>&1 && [ -f \$B/config.jsonc ]; then alw-gui-run waybar -c \$B/config.jsonc -s \$B/style.css >/tmp/rt/waybar.log 2>&1 & fi'\")")
            appendLine("    -- Live FPS / render-scale pill from the ALW host bridge.")
            appendLine("    hl.exec_cmd(\"sh -c 'F=/root/.config/quickshell/alw-fps; if command -v qs >/dev/null 2>&1 && [ -f \$F/shell.qml ]; then alw-gui-run qs -c alw-fps >/tmp/rt/quickshell-fps.log 2>&1 & fi'\")")
            appendLine("    -- Optional post-start hook (TASK-025): runs only if present.")
            appendLine("    hl.exec_cmd(\"sh -c 'test -x /root/alw-session-hook.sh && /root/alw-session-hook.sh > /tmp/rt/alw-session-hook.log 2>&1'\")")
            appendLine("end)")
        }
    }

    /**
     * Generates a clean default user configuration for Hyprland (~/.config/hypr/hyprland.conf).
     */
    fun generateDefaultHyprlandUserConfig(): String {
        return buildString {
            appendLine("# Xiaomi Pad 8 Default Hyprland Configuration")
            appendLine("# Managed by user; ALW sources this file before runtime overrides.")
            appendLine()
            appendLine("monitor = , preferred, auto, 1.75")
            appendLine()
            appendLine("\$terminal = kitty")
            appendLine("\$mainMod = SUPER")
            appendLine()
            appendLine("bind = \$mainMod, Return, exec, \$terminal")
            appendLine("bind = \$mainMod, Q, killactive,")
            appendLine("bind = \$mainMod, M, exit,")
            appendLine()
            appendLine("input {")
            appendLine("    kb_layout = us")
            appendLine("    follow_mouse = 1")
            appendLine("    touchpad {")
            appendLine("        natural_scroll = true")
            appendLine("    }")
            appendLine("    tablet {")
            appendLine("        output = WL-1")
            appendLine("    }")
            appendLine("    touchdevice {")
            appendLine("        output = WL-1")
            appendLine("    }")
            appendLine("}")
            appendLine()
            appendLine("general {")
            appendLine("    gaps_in = 4")
            appendLine("    gaps_out = 8")
            appendLine("    border_size = 2")
            appendLine("    col.active_border = rgba(33ccffee) rgba(00ff99ee) 45deg")
            appendLine("    col.inactive_border = rgba(595959aa)")
            appendLine("    layout = dwindle")
            appendLine("}")
            appendLine()
            appendLine("dwindle {")
            appendLine("    pseudotile = true")
            appendLine("    preserve_split = true")
            appendLine("}")
        }
    }

    /**
     * Generates a clean Openbox-compliant rc.xml for LabWC Safe Mode (~/.config/labwc/rc.xml).
     */
    fun generateDefaultLabwcRcXml(profile: StackProfile): String {
        return buildString {
            appendLine("<?xml version=\"1.0\"?>")
            appendLine("<labwc_config>")
            appendLine("  <theme>")
            appendLine("    <name>Openbox</name>")
            appendLine("    <titlebar>")
            appendLine("      <layout>NL:IMC</layout>")
            appendLine("    </titlebar>")
            appendLine("  </theme>")
            appendLine("  <core>")
            appendLine("    <decoration>server</decoration>")
            appendLine("    <gap>4</gap>")
            appendLine("  </core>")
            appendLine("  <windowRules>")
            appendLine("    <windowRule identifier=\"*\" serverDecoration=\"yes\" />")
            appendLine("  </windowRules>")
            appendLine("  <keyboard>")
            appendLine("    <keybind key=\"W-Return\"><action name=\"Execute\" command=\"weston-terminal --shell=/usr/bin/bash\" /></keybind>")
            appendLine("    <keybind key=\"A-Return\"><action name=\"Execute\" command=\"kitty\" /></keybind>")
            appendLine("    <keybind key=\"W-q\"><action name=\"Close\" /></keybind>")
            appendLine("    <keybind key=\"W-m\"><action name=\"Exit\" /></keybind>")
            appendLine("  </keyboard>")
            appendLine("  <touch>")
            appendLine("    <naturalScroll>${profile.input.touchpadNaturalScroll}</naturalScroll>")
            appendLine("  </touch>")
            appendLine("</labwc_config>")
        }
    }

    /**
     * Generates default autostart script for LabWC Safe Mode (~/.config/labwc/autostart).
     */
    fun generateDefaultLabwcAutostart(): String {
        return buildString {
            appendLine("#!/bin/sh")
            appendLine("# LabWC Safe Mode autostart")
            appendLine("which pipewire >/dev/null 2>&1 && pipewire &")
            appendLine("which wireplumber >/dev/null 2>&1 && wireplumber &")
            appendLine("if which weston-terminal >/dev/null 2>&1; then")
            appendLine("    weston-terminal --shell=/usr/bin/bash &")
            appendLine("elif which kitty >/dev/null 2>&1; then")
            appendLine("    kitty &")
            appendLine("elif which foot >/dev/null 2>&1; then")
            appendLine("    foot &")
            appendLine("fi")
        }
    }

    /**
     * Ensures default configs exist for the specified rootfs without overwriting existing user dotfiles.
     */
    fun ensureDefaultConfigsExist(rootfsDir: File, defaultUser: String, profile: StackProfile) {
        val userHome = File(rootfsDir, "home/$defaultUser")
        val hyprConfigDir = File(userHome, ".config/hypr")
        val hyprConfigFile = File(hyprConfigDir, "hyprland.conf")

        if (!hyprConfigFile.exists()) {
            hyprConfigDir.mkdirs()
            hyprConfigFile.writeText(generateDefaultHyprlandUserConfig())
        }

        val labwcConfigDir = File(userHome, ".config/labwc")
        val labwcConfigFile = File(labwcConfigDir, "rc.xml")
        val labwcAutostartFile = File(labwcConfigDir, "autostart")

        if (!labwcConfigFile.exists()) {
            labwcConfigDir.mkdirs()
            labwcConfigFile.writeText(generateDefaultLabwcRcXml(profile))
        }

        if (!labwcAutostartFile.exists()) {
            labwcConfigDir.mkdirs()
            labwcAutostartFile.writeText(generateDefaultLabwcAutostart())
            labwcAutostartFile.setExecutable(true, false)
        }
    }
}
